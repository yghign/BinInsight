/** id → 词条 的 O(1) 查表（术语浮层与核心概念页共用）。 */
export const GLOSSARY_BY_ID: Record<string, GlossEntry> = Object.fromEntries(
  GLOSSARY.map((entry) => [entry.id, entry])
);

/** 按 id 取词条；找不到返回 undefined（调用方必须兜底，不猜测）。 */
export function getGlossEntry(id: string): GlossEntry | undefined {
  return GLOSSARY_BY_ID[id];
}

/** 按别名/term 模糊查词条，供正文自动匹配使用。 */
export function findGlossEntry(word: string): GlossEntry | undefined {
  const needle = word.trim().toLowerCase();
  return GLOSSARY.find(
    (entry) =>
      entry.id === needle ||
      entry.term.toLowerCase() === needle ||
      entry.aliases.some((alias) => alias.toLowerCase() === needle)
  );
}

