/** 同步取轻量元数据（method 卡直接给完整数据，vuln 卡给列表项）。 */
export function getLibraryItem(id: string): LibraryListItem | MethodCard | undefined {
  const method = METHOD_CARDS.find((m) => m.id === id);
  if (method) return method;
  return LIBRARY_LIST.find((item) => item.id === id);
}

/**
 * 详情页按章加载完整条目的正文。
 * 通过 LOADERS[chapter] 静态 chunk 取对应章数组，再按 id 精确定位。
 */
export async function loadFullEntry(id: string): Promise<LibraryItem | undefined> {
  const method = METHOD_CARDS.find((m) => m.id === id);
  if (method) return method;
  const meta = LIBRARY_LIST.find((item) => item.id === id);
  if (!meta || meta.kind !== 'vuln') return undefined;
  const loader = LOADERS[`ch${meta.chapter}`];
  if (!loader) return undefined;
  const module = await loader();
  // ch0.ts 默认导出 ch0Entries，ch1.ts 默认导出 ch1Entries
  const entries = (module.default ?? module[`ch${meta.chapter}Entries`]) as LearningEntry[] | undefined;
  if (!Array.isArray(entries)) return undefined;
  return entries.find((entry) => entry.id === id);
}
